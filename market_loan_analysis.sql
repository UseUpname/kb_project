-- ------------------------------------------------------------------------------
-- VIEW 1: VW_CUSTOMER_LOAN_SUMMARY
-- 설명: 고객(customer_id) 단위로 고유화하여 중복 없는 고객별 대출 및 기본 속성을 제공
-- ------------------------------------------------------------------------------
CREATE OR REPLACE VIEW VW_CUSTOMER_LOAN_SUMMARY AS
SELECT 
    customer_id,
    행정동_코드,
    지역 AS 행정동_명,
    업종,
    대출_보유_여부,
    대출_종류,
    대출_잔액,
    가상_고객_매출_금액,
    가상_고객_매출_증감률,
    TO_CHAR(행정동_코드) || '_' || 업종 AS 상권_비교키
FROM CUSTOMER_FINANCIAL_PRODUCTS
GROUP BY 
    customer_id,
    행정동_코드,
    지역,
    업종,
    대출_보유_여부,
    대출_종류,
    대출_잔액,
    가상_고객_매출_금액,
    가상_고객_매출_증감률;


-- ------------------------------------------------------------------------------
-- VIEW 2: VW_MARKET_SALES_TREND
-- 설명: 상권별(행정동 코드 + 업종군) 시계열 매출 및 성장률(YoY, QoQ) 집계 뷰
-- ------------------------------------------------------------------------------
CREATE OR REPLACE VIEW VW_MARKET_SALES_TREND AS
WITH quarterly_sales AS (
    SELECT 
        행정동_코드,
        행정동_코드_명,
        업종군 AS 업종,
        TO_CHAR(행정동_코드) || '_' || 업종군 AS 상권_비교키,
        -- 최신 분기 (2025년 4분기)
        MAX(CASE WHEN 기준_년분기_코드 = 20254 THEN 당월_매출_금액 END) AS 상권_매출_20254,
        MAX(CASE WHEN 기준_년분기_코드 = 20254 THEN 당월_매출_건수 END) AS 상권_건수_20254,
        -- 전년 동기 (2024년 4분기)
        MAX(CASE WHEN 기준_년분기_코드 = 20244 THEN 당월_매출_금액 END) AS 상권_매출_20244,
        MAX(CASE WHEN 기준_년분기_코드 = 20244 THEN 당월_매출_건수 END) AS 상권_건수_20244,
        -- 직전 분기 (2025년 3분기)
        MAX(CASE WHEN 기준_년분기_코드 = 20253 THEN 당월_매출_금액 END) AS 상권_매출_20253,
        MAX(CASE WHEN 기준_년분기_코드 = 20253 THEN 당월_매출_건수 END) AS 상권_건수_20253,
        -- 3개년 12분기 전체 평균 분기 매출
        ROUND(AVG(당월_매출_금액), 0) AS 상권_3개년_분기평균매출,
        ROUND(AVG(당월_매출_건수), 0) AS 상권_3개년_분기평균건수
    FROM MARKET_SALES_RAW
    GROUP BY 행정동_코드, 행정동_코드_명, 업종군
)
SELECT 
    행정동_코드,
    행정동_코드_명,
    업종,
    상권_비교키,
    상권_매출_20254,
    상권_건수_20254,
    상권_매출_20244,
    상권_매출_20253,
    상권_3개년_분기평균매출,
    상권_3개년_분기평균건수,
    -- YoY 증감률 (전년 동기 대비)
    ROUND(((상권_매출_20254 - 상권_매출_20244) / NULLIF(상권_매출_20244, 0)) * 100, 2) AS 상권_매출_YOY_증감률,
    -- QoQ 증감률 (직전 분기 대비)
    ROUND(((상권_매출_20254 - 상권_매출_20253) / NULLIF(상권_매출_20253, 0)) * 100, 2) AS 상권_매출_QOQ_증감률,
    -- 상권 건수 YoY 증감률
    ROUND(((상권_건수_20254 - 상권_건수_20244) / NULLIF(상권_건수_20244, 0)) * 100, 2) AS 상권_건수_YOY_증감률,
    -- 상권 매출 추세 유형화
    CASE 
        WHEN 상권_매출_20254 < 상권_매출_20244 AND 상권_매출_20254 < 상권_매출_20253 THEN '지속감소(위험)'
        WHEN 상권_매출_20254 < 상권_매출_20244 AND 상권_매출_20254 >= 상권_매출_20253 THEN '단기반등'
        WHEN 상권_매출_20254 >= 상권_매출_20244 AND 상권_매출_20254 < 상권_매출_20253 THEN '단기둔화'
        ELSE '지속성장'
    END AS 상권_매출_추세
FROM quarterly_sales;


-- ------------------------------------------------------------------------------
-- VIEW 3: VW_MARKET_LOAN_ANALYSIS (핵심 통합 뷰)
-- 설명: 행정동·업종별 상권 매출 지표와 당행 소상공인 대출잔액 결합 종합 분석 뷰
-- ------------------------------------------------------------------------------
CREATE OR REPLACE VIEW VW_MARKET_LOAN_ANALYSIS AS
WITH agg_cust_loan AS (
    SELECT 
        상권_비교키,
        COUNT(customer_id) AS 당행_고객수,
        SUM(CASE WHEN 대출_보유_여부 = 'Y' THEN 1 ELSE 0 END) AS 대출_보유_고객수,
        SUM(대출_잔액) AS 총_대출잔액,
        ROUND(AVG(CASE WHEN 대출_보유_여부 = 'Y' THEN 대출_잔액 END), 0) AS 대출고객_평균_대출잔액,
        SUM(CASE WHEN 대출_종류 = '운전자금대출' THEN 대출_잔액 ELSE 0 END) AS 운전자금_대출잔액,
        SUM(CASE WHEN 대출_종류 = '시설자금대출' THEN 대출_잔액 ELSE 0 END) AS 시설자금_대출잔액,
        SUM(CASE WHEN 대출_종류 = '소상공인신용대출' THEN 대출_잔액 ELSE 0 END) AS 신용대출_잔액,
        ROUND(AVG(가상_고객_매출_금액), 0) AS 고객_평균매출액,
        ROUND(AVG(가상_고객_매출_증감률), 2) AS 고객_평균_매출증감률,
        SUM(CASE WHEN 가상_고객_매출_증감률 < 0 THEN 1 ELSE 0 END) AS 매출감소_고객수
    FROM VW_CUSTOMER_LOAN_SUMMARY
    GROUP BY 상권_비교키
)
SELECT 
    m.행정동_코드,
    m.행정동_코드_명,
    m.업종,
    m.상권_비교키,
    m.상권_매출_20254,
    m.상권_건수_20254,
    m.상권_매출_YOY_증감률,
    m.상권_매출_QOQ_증감률,
    m.상권_매출_추세,
    NVL(c.당행_고객수, 0) AS 당행_고객수,
    NVL(c.대출_보유_고객수, 0) AS 대출_보유_고객수,
    CASE 
        WHEN NVL(c.당행_고객수, 0) > 0 
        THEN ROUND((c.대출_보유_고객수 / c.당행_고객수) * 100, 2)
        ELSE 0 
    END AS 대출_보유율,
    NVL(c.총_대출잔액, 0) AS 총_대출잔액,
    NVL(c.대출고객_평균_대출잔액, 0) AS 대출고객_평균_대출잔액,
    NVL(c.운전자금_대출잔액, 0) AS 운전자금_대출잔액,
    NVL(c.시설자금_대출잔액, 0) AS 시설자금_대출잔액,
    NVL(c.신용대출_잔액, 0) AS 신용대출_잔액,
    NVL(c.고객_평균매출액, 0) AS 고객_평균매출액,
    NVL(c.고객_평균_매출증감률, 0) AS 고객_평균_매출증감률,
    NVL(c.매출감소_고객수, 0) AS 매출감소_고객수,
    -- 종합 위험 신호 등급 분류 (은행원 모니터링 기준)
    CASE 
        WHEN m.상권_매출_YOY_증감률 < -10.0 AND NVL(c.총_대출잔액, 0) >= 30000000 
            THEN '고위험(매출급감/대출집중)'
        WHEN m.상권_매출_YOY_증감률 < 0 AND NVL(c.총_대출잔액, 0) > 0 
            THEN '주의(매출감소/대출보유)'
        WHEN m.상권_매출_YOY_증감률 < 0 AND NVL(c.총_대출잔액, 0) = 0 
            THEN '관찰(매출감소/대출무)'
        ELSE '정상'
    END AS 상권_위험_등급
FROM VW_MARKET_SALES_TREND m
LEFT JOIN agg_cust_loan c ON m.상권_비교키 = c.상권_비교키;


-- ------------------------------------------------------------------------------
-- VIEW 4: VW_HIGH_RISK_MARKET_LOAN
-- 설명: 은행원이 우선 점검해야 할 상권 매출 감소 & 대출 집중 고위험 상권 추출 뷰
-- ------------------------------------------------------------------------------
CREATE OR REPLACE VIEW VW_HIGH_RISK_MARKET_LOAN AS
SELECT 
    행정동_코드,
    행정동_코드_명,
    업종,
    상권_매출_20254,
    상권_매출_YOY_증감률,
    상권_매출_QOQ_증감률,
    상권_매출_추세,
    당행_고객수,
    대출_보유_고객수,
    대출_보유율,
    총_대출잔액,
    대출고객_평균_대출잔액,
    운전자금_대출잔액,
    시설자금_대출잔액,
    신용대출_잔액,
    고객_평균_매출증감률,
    상권_위험_등급
FROM VW_MARKET_LOAN_ANALYSIS
WHERE 당행_고객수 > 0
  AND 상권_위험_등급 IN ('고위험(매출급감/대출집중)', '주의(매출감소/대출보유)')
ORDER BY 총_대출잔액 DESC, 상권_매출_YOY_증감률 ASC;


-- ==============================================================================
-- 3. 핵심 비즈니스 질문별 심층 분석 쿼리 (SELECT)
-- ==============================================================================

-- ------------------------------------------------------------------------------
-- [쿼리 1] 서울시 11개 업종별 상권 매출 증감률 및 대출 잔액 현황 총괄
-- 설명: 어떤 업종에서 상권 매출이 위축되고 대출 잔액이 집중되어 있는지 파악
-- ------------------------------------------------------------------------------
SELECT 
    업종,
    COUNT(DISTINCT 행정동_코드) AS 총_상권수,
    ROUND(AVG(상권_매출_YOY_증감률), 2) AS 평균_상권매출_YOY_증감률,
    ROUND(AVG(상권_매출_QOQ_증감률), 2) AS 평균_상권매출_QOQ_증감률,
    SUM(당행_고객수) AS 업종별_고객수,
    SUM(대출_보유_고객수) AS 업종별_대출고객수,
    ROUND((SUM(대출_보유_고객수) / NULLIF(SUM(당행_고객수), 0)) * 100, 2) AS 대출_보유율_PCT,
    SUM(총_대출잔액) AS 업종별_총_대출잔액,
    ROUND(AVG(NULLIF(총_대출잔액, 0)), 0) AS 상권당_평균_대출잔액,
    SUM(운전자금_대출잔액) AS 총_운전자금_대출잔액,
    SUM(시설자금_대출잔액) AS 총_시설자금_대출잔액,
    SUM(신용대출_잔액) AS 총_신용대출_잔액
FROM VW_MARKET_LOAN_ANALYSIS
GROUP BY 업종
ORDER BY 업종별_총_대출잔액 DESC;


-- ------------------------------------------------------------------------------
-- [쿼리 2] 상권 매출 감소율(YoY)이 가장 심각한 행정동 TOP 10 및 대출잔액
-- 설명: 매출이 급격히 줄어든 취약 지역의 대출 규모 확인
-- ------------------------------------------------------------------------------
SELECT 
    행정동_코드,
    행정동_코드_명,
    ROUND(AVG(상권_매출_YOY_증감률), 2) AS 행정동_평균_매출_YOY_증감률,
    ROUND(AVG(상권_매출_QOQ_증감률), 2) AS 행정동_평균_매출_QOQ_증감률,
    SUM(당행_고객수) AS 고객수,
    SUM(대출_보유_고객수) AS 대출_고객수,
    SUM(총_대출잔액) AS 행정동_총_대출잔액,
    SUM(운전자금_대출잔액) AS 행정동_운전자금대출,
    COUNT(CASE WHEN 상권_위험_등급 LIKE '%위험%' THEN 1 END) AS 고위험_상권수
FROM VW_MARKET_LOAN_ANALYSIS
GROUP BY 행정동_코드, 행정동_코드_명
HAVING SUM(당행_고객수) > 0
ORDER BY 행정동_평균_매출_YOY_증감률 ASC
FETCH FIRST 10 ROWS ONLY;


-- ------------------------------------------------------------------------------
-- [쿼리 3] 총 대출잔액 상위 10개 상권(행정동-업종)의 매출 및 위험 현황
-- 설명: 은행 입장에서 익스포저(대출 규모)가 큰 상권의 매출 상태 점검
-- ------------------------------------------------------------------------------
SELECT 
    행정동_코드_명,
    업종,
    총_대출잔액,
    당행_고객수,
    대출_보유_고객수,
    대출_보유율,
    상권_매출_20254,
    상권_매출_YOY_증감률,
    상권_매출_추세,
    고객_평균_매출증감률,
    상권_위험_등급
FROM VW_MARKET_LOAN_ANALYSIS
WHERE 당행_고객수 > 0
ORDER BY 총_대출잔액 DESC
FETCH FIRST 10 ROWS ONLY;


-- ------------------------------------------------------------------------------
-- [쿼리 4] 대출 종류별(운전, 시설, 신용) 리스크 분포 현황
-- 설명: 매출 감소 상권에 투입된 대출 성격(운전자금 대출 비중 등) 분석
-- ------------------------------------------------------------------------------
SELECT 
    상권_매출_추세,
    COUNT(상권_비교키) AS 상권수,
    SUM(당행_고객수) AS 총_고객수,
    SUM(대출_보유_고객수) AS 대출고객수,
    SUM(총_대출잔액) AS 합계_대출잔액,
    SUM(운전자금_대출잔액) AS 합계_운전자금잔액,
    ROUND((SUM(운전자금_대출잔액) / NULLIF(SUM(총_대출잔액), 0)) * 100, 2) AS 운전자금_비중_PCT,
    SUM(시설자금_대출잔액) AS 합계_시설자금잔액,
    ROUND((SUM(시설자금_대출잔액) / NULLIF(SUM(총_대출잔액), 0)) * 100, 2) AS 시설자금_비중_PCT,
    SUM(신용대출_잔액) AS 합계_신용대출잔액,
    ROUND((SUM(신용대출_잔액) / NULLIF(SUM(총_대출잔액), 0)) * 100, 2) AS 신용대출_비중_PCT
FROM VW_MARKET_LOAN_ANALYSIS
WHERE 당행_고객수 > 0
GROUP BY 상권_매출_추세
ORDER BY 합계_대출잔액 DESC;


-- ------------------------------------------------------------------------------
-- [쿼리 5] 은행원 우선 상담/사후관리 추천 대상: 고위험 13개 상권 상세 명세
-- 설명: 상권 매출 급감(YoY < -10%) + 대출 집중(3,000만 원 이상) 상권 목록
-- (최종 대시보드 API: GET /api/risk 및 GET /api/market 에 직접 바인딩 가능)
-- ------------------------------------------------------------------------------
SELECT 
    행정동_코드,
    행정동_코드_명,
    업종,
    상권_매출_YOY_증감률,
    상권_매출_QOQ_증감률,
    당행_고객수,
    대출_보유_고객수,
    총_대출잔액,
    운전자금_대출잔액,
    시설자금_대출잔액,
    신용대출_잔액,
    고객_평균_매출증감률,
    매출감소_고객수,
    CASE 
        WHEN 상권_매출_YOY_증감률 < -20.0 THEN '즉시 점검(매출 -20% 이상 급락)'
        ELSE '중점 관리(매출 -10% 이상 감소)'
    END AS 상담_우선순위_가이드
FROM VW_MARKET_LOAN_ANALYSIS
WHERE 상권_위험_등급 = '고위험(매출급감/대출집중)'
ORDER BY 상권_매출_YOY_증감률 ASC, 총_대출잔액 DESC;
